"""Step 2 of the paper: can offline RL use a known signal? (Section 3, Figure 2)

    python scripts/learning_test.py collect           # rebuild report + Figure 2 data from
                                                      # the 90 published worker files (seconds)
    python scripts/learning_test.py run --workers 4   # retrain all 90 policies from scratch
                                                      # (~30 min on 4 cores, needs torch)
    python scripts/learning_test.py smoke             # tiny end-to-end run (~10 s)

``collect`` reads ``results/learning/workers/`` (the published runs) and rewrites
``results/learning/report.json`` and ``results/learning/capability_common_flat.csv``.

``run`` trains into ``results/learning/rerun/`` so the published files are never
overwritten, then prints your numbers next to the paper's. PyTorch training is not
bit-for-bit portable across platforms and BLAS builds: on Linux, 79 of the 90 runs match
the published (Windows) runs to 1e-6 and the rest within 0.5%; every number reported in
the paper and every decision is unchanged.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
from pathlib import Path

from catch_alpha.learning import experiment

ROOT = Path(__file__).resolve().parents[1]
LEARNING = ROOT / "results" / "learning"

# (arm, policy label, cost cell) rows of the Figure 2 table
FIGURE_ARMS = (
    ("bc_lam0", "BC", "no_cost"),
    ("iql_lam0", "IQL", "no_cost"),
    ("cql_lam0", "CQL", "no_cost"),
    ("bc_lam1", "BC", "cost"),
    ("iql_lam1", "IQL", "cost"),
    ("cql_lam1", "CQL", "cost"),
    ("bc_pos_lam1", "BC + previous position", "cost"),
)

# Numbers printed in the paper (Section 3), for the side-by-side comparison.
PAPER = {
    ("bc_lam0", "median_recovery"): 0.900,
    ("iql_lam0", "median_recovery"): 0.731,
    ("cql_lam0", "median_recovery"): 0.335,
    ("bc_lam1", "median_mean_pnl"): -0.995,
    ("iql_lam1", "median_mean_pnl"): -4.036,
    ("bc_lam1", "median_turnover_ratio"): 6.03,
    ("iql_lam1", "median_turnover_ratio"): 11.97,
    ("bc_pos_lam1", "median_mean_pnl"): -0.960,
    ("bc_pos_lam1", "median_turnover_ratio"): 5.92,
}


def load_workers(worker_dir: Path) -> list[dict]:
    paths = sorted(worker_dir.glob("E240_*_s*.json"))
    return [json.loads(p.read_text(encoding="utf-8")) for p in paths]


def reference_mean(workers: list[dict]) -> float:
    """GP mean profit with costs (identical in every cost worker: same 100 paths)."""
    worker = next(w for w in workers if w["arm"]["name"] == "bc_lam1" and w["training_seed"] == 0)
    gate = worker["summary"]["denominator_gate"]
    if not gate["recovery_identifiable"]:
        raise AssertionError("the GP reference denominator is not admissible")
    return float(worker["summary"]["reference_pnl_mean"])


def figure_csv(report: dict, gp_cost_mean: float) -> str:
    """Figure 2 input, same schema as the paper's capability_common_flat.csv."""
    stream = io.StringIO(newline="")
    stream.write(
        "# generated by scripts/learning_test.py from report.json and one cost-cell worker\n"
    )
    fields = [
        "policy",
        "cell",
        "median_recovery",
        "median_mean_pnl",
        "negative_training_seeds",
        "n_training_seeds",
        "median_turnover_ratio",
        "sanity_pass",
        "adjudication",
    ]
    writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
    writer.writeheader()
    decisions = report["decisions"]
    for arm, policy, cell in FIGURE_ARMS:
        agg = report["aggregates"][arm]
        if arm.startswith("bc_pos"):
            rescued = bool(decisions["bc_position_aware"]["rescue"])
            sanity, verdict = "not_applicable", ("rescued" if rescued else "rescue_failed")
        else:
            family = arm.split("_", maxsplit=1)[0]
            sanity = str(decisions[family]["frictionless_sanity"]).lower()
            verdict = str(decisions[family]["verdict"])
        writer.writerow(
            {
                "policy": policy,
                "cell": cell,
                "median_recovery": agg["median_recovery"],
                "median_mean_pnl": agg["median_mean_pnl"],
                "negative_training_seeds": agg["n_negative_training_seeds"],
                "n_training_seeds": len(report["contract"]["training_seeds"]),
                "median_turnover_ratio": agg["median_turnover_ratio"],
                "sanity_pass": sanity,
                "adjudication": verdict,
            }
        )
    for cell, pnl in (("no_cost", ""), ("cost", gp_cost_mean)):
        writer.writerow(
            {
                "policy": "GP reference",
                "cell": cell,
                "median_recovery": 1.0,
                "median_mean_pnl": pnl,
                "negative_training_seeds": "",
                "n_training_seeds": "",
                "median_turnover_ratio": 1.0,
                "sanity_pass": "reference",
                "adjudication": "reference",
            }
        )
    return stream.getvalue()


def collect_into(worker_dir: Path, out_dir: Path) -> dict:
    workers = load_workers(worker_dir)
    report = experiment.collect(workers)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "report.json").write_text(json.dumps(report, indent=1) + "\n", encoding="utf-8")
    gp_mean = reference_mean(workers)
    (out_dir / "capability_common_flat.csv").write_text(
        figure_csv(report, gp_mean), encoding="utf-8", newline=""
    )
    print(f"wrote {out_dir.relative_to(ROOT)}/report.json and capability_common_flat.csv")
    print_comparison(report, gp_mean)
    return report


def print_comparison(report: dict, gp_mean: float) -> None:
    print(f"\n{'quantity':45s} {'paper':>9s} {'this run':>12s}")
    for (arm, key), paper in PAPER.items():
        value = report["aggregates"][arm][key]
        print(f"{arm + ' ' + key:45s} {paper:9.3f} {value:12.5f}")
    print(f"{'GP reference mean profit with costs':45s} {0.0461:9.4f} {gp_mean:12.6f}")
    for family in ("bc", "iql", "cql"):
        d = report["decisions"][family]
        print(
            f"{family.upper():4s} no-cost check: {d['frictionless_sanity']!s:5s}  verdict: {d['verdict']}"
        )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("command", choices=["collect", "run", "smoke"])
    parser.add_argument("--workers", type=int, default=2, help="parallel training processes")
    args = parser.parse_args()

    if args.command == "smoke":
        experiment.main(["--smoke"])
    elif args.command == "collect":
        collect_into(LEARNING / "workers", LEARNING)
    else:
        rerun = LEARNING / "rerun"
        code = experiment.run_all(rerun / "workers", parallel=args.workers)
        if code:
            raise SystemExit(code)
        collect_into(rerun / "workers", rerun)


if __name__ == "__main__":
    main()
